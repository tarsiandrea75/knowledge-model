#!/usr/bin/env python3
"""Render deterministic RKM Codex profile files."""

from __future__ import annotations

import argparse
import json
import os
import sys
import tempfile
import tomllib
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Mapping, Sequence

PROFILE_ORDER = (
    "rkm-mechanical",
    "rkm-bounded",
    "rkm-engineering",
    "rkm-strategic",
)

DEFAULT_MODELS = {
    "rkm-mechanical": "gpt-5.4-mini",
    "rkm-bounded": "gpt-5.6-luna",
    "rkm-engineering": "gpt-5.6-terra",
    "rkm-strategic": "gpt-5.6-sol",
}

DEFAULT_REASONING = {
    "rkm-mechanical": "low",
    "rkm-bounded": "low",
    "rkm-engineering": "medium",
    "rkm-strategic": "high",
}

MODEL_ENVIRONMENT = {
    "rkm-mechanical": "RKM_CODEX_MODEL_MECHANICAL",
    "rkm-bounded": "RKM_CODEX_MODEL_BOUNDED",
    "rkm-engineering": "RKM_CODEX_MODEL_ENGINEERING",
    "rkm-strategic": "RKM_CODEX_MODEL_STRATEGIC",
}

REASONING_ENVIRONMENT = {
    "rkm-mechanical": "RKM_CODEX_REASONING_MECHANICAL",
    "rkm-bounded": "RKM_CODEX_REASONING_BOUNDED",
    "rkm-engineering": "RKM_CODEX_REASONING_ENGINEERING",
    "rkm-strategic": "RKM_CODEX_REASONING_STRATEGIC",
}

SEMANTIC_TIERS = {
    "rkm-mechanical": 1,
    "rkm-bounded": 2,
    "rkm-engineering": 3,
    "rkm-strategic": 4,
}

REASONING_CHOICES = ("minimal", "low", "medium", "high", "xhigh")


@dataclass(frozen=True)
class ProfileBinding:
    name: str
    semantic_tier: int
    model: str
    reasoning_effort: str
    filename: str


@dataclass(frozen=True)
class RenderResult:
    mode: str
    output_directory: str
    profiles: list[ProfileBinding]
    created: list[str]
    updated: list[str]
    unchanged: list[str]


def validate_model(value: str) -> str:
    model = value.strip()
    if not model:
        raise ValueError("model binding must not be empty")
    if any(character.isspace() for character in model):
        raise ValueError(f"model binding must not contain whitespace: {value!r}")
    return model


def validate_reasoning(value: str) -> str:
    effort = value.strip().lower()
    if effort not in REASONING_CHOICES:
        allowed = ", ".join(REASONING_CHOICES)
        raise ValueError(
            f"invalid reasoning effort {value!r}; expected one of: {allowed}"
        )
    return effort


def parse_overrides(
    values: Sequence[str] | None,
    *,
    label: str,
) -> dict[str, str]:
    overrides: dict[str, str] = {}
    for raw_value in values or ():
        profile, separator, value = raw_value.partition("=")
        profile = profile.strip()
        value = value.strip()
        if separator != "=" or not profile or not value:
            raise ValueError(f"{label} override must use profile=value syntax")
        if profile not in PROFILE_ORDER:
            allowed = ", ".join(PROFILE_ORDER)
            raise ValueError(
                f"unknown profile {profile!r}; expected one of: {allowed}"
            )
        if profile in overrides:
            raise ValueError(f"duplicate {label} override for {profile}")
        overrides[profile] = value
    return overrides


def resolve_bindings(
    *,
    model_overrides: Mapping[str, str] | None = None,
    reasoning_overrides: Mapping[str, str] | None = None,
    environment: Mapping[str, str] | None = None,
) -> list[ProfileBinding]:
    model_overrides = model_overrides or {}
    reasoning_overrides = reasoning_overrides or {}
    environment = environment or os.environ
    bindings: list[ProfileBinding] = []

    for profile in PROFILE_ORDER:
        model = model_overrides.get(
            profile,
            environment.get(
                MODEL_ENVIRONMENT[profile],
                DEFAULT_MODELS[profile],
            ),
        )
        reasoning = reasoning_overrides.get(
            profile,
            environment.get(
                REASONING_ENVIRONMENT[profile],
                DEFAULT_REASONING[profile],
            ),
        )
        bindings.append(
            ProfileBinding(
                name=profile,
                semantic_tier=SEMANTIC_TIERS[profile],
                model=validate_model(model),
                reasoning_effort=validate_reasoning(reasoning),
                filename=f"{profile}.config.toml",
            )
        )
    return bindings


def render_profile(binding: ProfileBinding) -> str:
    model = json.dumps(binding.model, ensure_ascii=False)
    effort = json.dumps(binding.reasoning_effort, ensure_ascii=False)
    return (
        "# Generated by scripts/rkm-render-codex-profiles.py.\n"
        "# Exact model bindings remain configurable operational values.\n"
        f"# RKM semantic tier: {binding.semantic_tier}.\n"
        f"model = {model}\n"
        f"model_reasoning_effort = {effort}\n"
    )


def validate_content(binding: ProfileBinding, content: str) -> None:
    parsed = tomllib.loads(content)
    expected = {
        "model": binding.model,
        "model_reasoning_effort": binding.reasoning_effort,
    }
    if parsed != expected:
        raise ValueError(f"rendered profile {binding.name} is invalid")
    if not content.endswith("\n"):
        raise ValueError(f"rendered profile {binding.name} lacks final newline")
    if any(line.rstrip() != line for line in content.splitlines()):
        raise ValueError(f"rendered profile {binding.name} has trailing whitespace")


def atomic_write(path: Path, content: str) -> None:
    temporary = path.with_name(f".{path.name}.tmp-{os.getpid()}")
    try:
        temporary.write_text(content, encoding="utf-8", newline="\n")
        temporary.chmod(0o600)
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()


def render_profiles(
    output_directory: Path,
    bindings: Sequence[ProfileBinding],
    *,
    check: bool,
    force: bool,
) -> RenderResult:
    if check and force:
        raise ValueError("--check and --force cannot be combined")

    output = output_directory.expanduser().resolve()
    if check and not output.is_dir():
        raise FileNotFoundError(f"profile output directory is missing: {output}")
    if not check:
        output.mkdir(parents=True, exist_ok=True)

    created: list[str] = []
    updated: list[str] = []
    unchanged: list[str] = []

    for binding in bindings:
        content = render_profile(binding)
        validate_content(binding, content)
        target = output / binding.filename
        current = (
            target.read_text(encoding="utf-8")
            if target.exists()
            else None
        )

        if current == content:
            unchanged.append(binding.filename)
            continue
        if check:
            state = "missing" if current is None else "different"
            raise ValueError(f"{binding.filename} is {state}")
        if target.exists() and not force:
            raise FileExistsError(
                f"refusing to overwrite {target}; rerun with --force"
            )

        existed = target.exists()
        atomic_write(target, content)
        (updated if existed else created).append(binding.filename)

    return RenderResult(
        mode="check" if check else "render",
        output_directory=str(output),
        profiles=list(bindings),
        created=created,
        updated=updated,
        unchanged=unchanged,
    )


def result_as_text(result: RenderResult) -> str:
    lines = [
        "# RKM Codex Profile Rendering",
        "",
        f"- Mode: `{result.mode}`",
        f"- Output directory: `{result.output_directory}`",
        "",
    ]
    for binding in result.profiles:
        lines.extend(
            (
                f"## {binding.name}",
                "",
                f"- Tier: `{binding.semantic_tier}`",
                f"- Model: `{binding.model}`",
                f"- Reasoning effort: `{binding.reasoning_effort}`",
                f"- Filename: `{binding.filename}`",
                "",
            )
        )
    lines.extend(
        (
            "## File Results",
            "",
            f"- Created: `{', '.join(result.created) or 'none'}`",
            f"- Updated: `{', '.join(result.updated) or 'none'}`",
            f"- Unchanged: `{', '.join(result.unchanged) or 'none'}`",
        )
    )
    return "\n".join(lines) + "\n"


def run_self_test() -> None:
    empty_environment: dict[str, str] = {}
    defaults = resolve_bindings(environment=empty_environment)
    assert [item.model for item in defaults] == [
        "gpt-5.4-mini",
        "gpt-5.6-luna",
        "gpt-5.6-terra",
        "gpt-5.6-sol",
    ]
    assert [item.reasoning_effort for item in defaults] == [
        "low",
        "low",
        "medium",
        "high",
    ]

    with tempfile.TemporaryDirectory(
        prefix="rkm-codex-profiles-"
    ) as temporary_directory:
        output = Path(temporary_directory) / "profiles"
        first = render_profiles(
            output,
            defaults,
            check=False,
            force=False,
        )
        assert len(first.created) == 4

        checked = render_profiles(
            output,
            defaults,
            check=True,
            force=False,
        )
        assert len(checked.unchanged) == 4

        changed = resolve_bindings(
            model_overrides={"rkm-bounded": "custom-bounded"},
            reasoning_overrides={"rkm-bounded": "medium"},
            environment=empty_environment,
        )

        try:
            render_profiles(
                output,
                changed,
                check=False,
                force=False,
            )
        except FileExistsError:
            pass
        else:
            raise AssertionError("overwrite protection did not activate")

        forced = render_profiles(
            output,
            changed,
            check=False,
            force=True,
        )
        assert forced.updated == ["rkm-bounded.config.toml"]
        assert len(forced.unchanged) == 3

        parsed = tomllib.loads(
            (output / "rkm-bounded.config.toml").read_text(
                encoding="utf-8"
            )
        )
        assert parsed["model"] == "custom-bounded"
        assert parsed["model_reasoning_effort"] == "medium"

    environment = {
        "RKM_CODEX_MODEL_STRATEGIC": "custom-strategic",
        "RKM_CODEX_REASONING_STRATEGIC": "xhigh",
    }
    overridden = resolve_bindings(environment=environment)
    assert overridden[-1].model == "custom-strategic"
    assert overridden[-1].reasoning_effort == "xhigh"

    print("RKM Codex profile renderer self-test passed.")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument(
        "--model",
        action="append",
        metavar="PROFILE=MODEL",
    )
    parser.add_argument(
        "--reasoning",
        action="append",
        metavar="PROFILE=EFFORT",
    )
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--force", action="store_true")
    parser.add_argument(
        "--format",
        choices=("text", "json"),
        default="text",
    )
    parser.add_argument("--self-test", action="store_true")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)

    if args.self_test:
        run_self_test()
        return 0
    if args.output_dir is None:
        parser.error("--output-dir is required unless --self-test is used")

    try:
        bindings = resolve_bindings(
            model_overrides=parse_overrides(
                args.model,
                label="model",
            ),
            reasoning_overrides=parse_overrides(
                args.reasoning,
                label="reasoning",
            ),
        )
        result = render_profiles(
            args.output_dir,
            bindings,
            check=args.check,
            force=args.force,
        )
    except (FileExistsError, FileNotFoundError, ValueError) as exc:
        parser.error(str(exc))

    if args.format == "json":
        print(json.dumps(asdict(result), indent=2, sort_keys=True))
    else:
        print(result_as_text(result), end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
